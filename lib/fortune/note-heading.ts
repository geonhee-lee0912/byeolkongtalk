// lib/fortune/note-heading.ts — 모델이 본문 앞에 섹션 제목을 한 번 더 붙이는 습관 방어(순수).
// 🔴 daily 전용이 아니다 — monthly·saju_full·compat 프롬프트가 "note" 필드 설명에 daily 와
//    똑같은 "별콩이의 한마디" 리터럴을 쓰고, 그 화면들도 같은 제목을 하드코딩한다. 실제 관측은
//    daily 에서 됐지만 구조가 같아 형제 리포트도 같이 방어한다.

/** "별콩이의 한마디: …" → "…". 볼드(**…**)·콜론·전각 콜론·em dash·하이픈·줄바꿈을 구분자로 받는다.
 *  🔴 구분자는 **필수**다(`?` 를 붙이지 말 것) — 선택으로 두면 "별콩이의 한마디를 준비했어." 같은
 *     멀쩡한 문장이 "를 준비했어."로 잘려나간다. 못 벗기는 손해보다 훼손하는 손해가 훨씬 크다.
 *  🔴 줄바꿈이 구분자에 있는 이유 — good_days 프롬프트가 같은 모델에게 `## 별콩이의 한마디` 를
 *     독립 줄 헤딩으로 쓰라고 가르친다. 그 습관이 note 에 "제목+개행"으로 새어 나올 수 있다. */
export function stripNoteHeading(s: string): string {
  const out = s.replace(/^\s*\*{0,2}별콩이의\s*한마디\*{0,2}\s*[:：—\-\n]\s*/, "").trim();
  // 벗겨낸 뒤 아무것도 안 남으면(본문이 제목뿐이었던 경우) 원문을 살린다 — 빈 카드보다 낫다.
  return out || s.trim();
}
