// 공용 섹션 리포트 프롬프트 빌더 — 신규 텍스트 종목 다수가 공유(generic-report.ts 스키마와 짝).
// 각 종목은 title/intro/sections/note 만 정의하면 된다. 분량은 sections 개수 × 문장수가 만든다(가성비).
function genericGuide(opts: {
  title: string;
  intro: string;
  sections: { heading: string; spec: string }[];
  note: string;
  tone?: string; // 특수 톤 지시(예: 팩폭)
}): string {
  const lines: string[] = [];
  lines.push(`위 사주판을 가진 사람의 **${opts.title}** 리포트를 작성해줘.`);
  if (opts.tone) lines.push(opts.tone);
  lines.push(
    `이 리포트는 **아래 JSON 형식 하나만** 출력해. JSON 앞뒤에 설명·인사·코드펜스(\`\`\`) 붙이지 마. 오직 JSON 객체 하나만.`,
    ``,
    `{`,
    `  "intro": "<${opts.intro}>",`,
    `  "sections": [`
  );
  opts.sections.forEach((s, i) => {
    const comma = i < opts.sections.length - 1 ? "," : "";
    lines.push(`    { "heading": "${s.heading}", "body": "<${s.spec}>" }${comma}`);
  });
  lines.push(
    `  ],`,
    `  "note": "<${opts.note}>"`,
    `}`,
    ``,
    `[규칙] 모든 문장은 반말 친구 말투(호칭은 '너'). 단정적 예언 금지 — 흐름·가능성("~한 흐름이 보여","~해보면 좋아")으로. 사주 근거(일간·오행·기둥)를 구체적으로 녹이고, 물타기·반복·공허한 미사여구 금지(밀도로 채워라). sections 는 위 heading 순서·개수 그대로 전부 채워라. 따뜻한 마무리.\n[서식] intro 와 각 섹션 body 를 잡지 기사처럼 다채롭고 리듬감 있게 마크다운으로 써라(딱딱한 산문 벽 금지). ①굵게: 핵심 단어·구절을 문단마다 1~2곳 **굵게** 강조(한 문단 통째 굵게는 금지, 핵심만). ②문단: 관련된 2~4문장을 한 문단으로 묶고 문단 사이에만 빈 줄(\\n\\n) — 한 문장마다 띄우지 말 것. ③불릿: 강점·조심할 점·특징·조언처럼 나열되는 내용은 산문 대신 각 줄 "- " 로 시작하는 불릿으로 정리(어울리는 섹션에 3~5개). ④콜아웃: 그 섹션에서 가장 중요한 팁·한마디 1개를 "> " 로 시작하는 인용 줄로 뽑아라(섹션마다 최대 1개, 남발 금지). heading 은 맨 앞 이모지 1개 + 제목 유지. 형식(굵게·불릿·콜아웃)을 내용에 맞게 섞어 지루하지 않게 — 단 억지로 다 넣지는 말 것. JSON 문자열 안에서 큰따옴표는 escape(\\")하고, 줄바꿈은 반드시 \\n 으로 이스케이프해라(생 줄바꿈 금지).`
  );
  return lines.join("\n");
}

