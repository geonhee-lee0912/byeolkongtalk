/** 그해 윤달 월(1~12). 없으면 0. 표 범위 밖도 0. */
export function lunarLeapMonth(year: number): number {
  return TABLE[year - LUNAR_TABLE_START]?.[0] ?? 0;
}

// 그해 대소월 문자열에서 이 달의 자리. 윤달이 있는 해는 윤달과 그 뒤 달들이 한 칸씩 밀린다.
function monthIndex(leap: number, month: number, isLeap: boolean): number {
  const shifted = leap !== 0 && (month > leap || (isLeap && month === leap));
  return month - 1 + (shifted ? 1 : 0);
}

/** 음력 그달 일수(29|30). 없는 달(그해 윤달이 아닌데 isLeap, 월이 1~12 정수가 아님, 표 범위 밖)은 0. */
export function lunarMonthDays(year: number, month: number, isLeap: boolean): number {
  const row = TABLE[year - LUNAR_TABLE_START];
  if (!row || !Number.isInteger(month) || month < 1 || month > 12) return 0;
  const [leap, bits] = row;
  if (isLeap && leap !== month) return 0;
  return bits[monthIndex(leap, month, isLeap)] === "1" ? 30 : 29;
}

// 음력 1900-01-01 = 양력 1900-01-31(KASI). 표의 달은 끊김 없이 이어지므로 그 뒤는 누적 일수로 정해진다.
const EPOCH_DAY = Date.UTC(1900, 0, 31) / 86_400_000;
// 해마다 그해 정월 초하루까지의 누적 일수(인덱스 = 연도 − LUNAR_TABLE_START).
const YEAR_START_DAY: readonly number[] = (() => {
  let acc = 0;
  return TABLE.map(([, bits]) => {
    const start = acc;
    for (const b of bits) acc += b === "1" ? 30 : 29;
    return start;
  });
})();

/**
 * 음력 → 양력(KASI 기준). 없는 날짜(그달 일수 밖, 그해 윤달이 아닌 isLeap, 표 범위 밖, 정수 아님)는 null.
 * 🔴 사주 계산의 음력 변환은 이것만 쓴다 — tyme4ts 의 음력은 중국 농력이다(calc.ts).
 */
export function lunarToSolar(
  year: number,
  month: number,
  day: number,
  isLeap: boolean
): { year: number; month: number; day: number } | null {
  const days = lunarMonthDays(year, month, isLeap);
  if (days === 0 || !Number.isInteger(day) || day < 1 || day > days) return null;
  const [leap, bits] = TABLE[year - LUNAR_TABLE_START];
  let offset = YEAR_START_DAY[year - LUNAR_TABLE_START];
  for (let i = 0; i < monthIndex(leap, month, isLeap); i++) offset += bits[i] === "1" ? 30 : 29;
  const d = new Date((EPOCH_DAY + offset + day - 1) * 86_400_000);
  return { year: d.getUTCFullYear(), month: d.getUTCMonth() + 1, day: d.getUTCDate() };
}

/**
 * 생년월일 폼이 보여줄 마지막 날. 월은 1~12 정수 전제.
 * - 양력: 그 월 일수.
 * - 음력: min(음력 그달 일수, 같은 숫자 월의 양력 일수). 🔴 뒤쪽은 user_profiles.birth_date 가 DATE 컬럼이라서다 —
 *   음력도 그레고리력에 있는 Y-M-D 만 저장된다(음력 2/30 → 22008). isLeap 은 그해 윤달이 이 달일 때만 적용.
 *   표 범위(1900~2049) 밖 음력은 0 — 호출부(폼)는 그 해를 보여주지 않는다.
 */
export function maxBirthDay(year: number, month: number, isLunar: boolean, isLeap: boolean): number {
  // UTC 로 센다 — 로컬 Date 는 날짜변경선을 옮긴 존(Pacific/Kiritimati 1994-12)에서 말일을 잘못 낸다.
  const solarDays = new Date(Date.UTC(year, month, 0)).getUTCDate(); // month 는 1-based → 다음 달 0일 = 이 달 말일
  if (!isLunar) return solarDays;
  const useLeap = isLeap && lunarLeapMonth(year) === month;
  return Math.min(lunarMonthDays(year, month, useLeap), solarDays);
}
