// 공유 훅 제목 — 마지막 글자 받침 있으면 "이래", 없으면 "래" (해동청→해동청이래)
export function shareHook(character: string): string {
  const last = character.charCodeAt(character.length - 1);
  const hasBatchim = last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0;
  return `나 ${character}${hasBatchim ? "이" : ""}래, 넌?`;
}

